void Capstone2LlvmIrTranslatorRiscv_impl::initializePseudoCallInstructionIDs()
{
	_callInsnIds =
	{
			RISCV_INS_JAL,
			RISCV_INS_JALR,
			RISCV_INS_C_JAL,
			RISCV_INS_C_JALR,
			RISCV_INS_ECALL,
	};

	_returnInsnIds =
	{
			// jalr x0, ra, 0 is classified at translation time.
	};

	_branchInsnIds =
	{
			RISCV_INS_C_J,
			RISCV_INS_C_JR,
	};

	_condBranchInsnIds =
	{
			RISCV_INS_BEQ,
			RISCV_INS_BNE,
			RISCV_INS_BLT,
			RISCV_INS_BGE,
			RISCV_INS_BLTU,
			RISCV_INS_BGEU,
			RISCV_INS_C_BEQZ,
			RISCV_INS_C_BNEZ,
	};

	_controlFlowInsnIds =
	{
			RISCV_INS_JAL,
			RISCV_INS_JALR,
			RISCV_INS_CM_JT,
			RISCV_INS_CM_JALT,
	};
}

