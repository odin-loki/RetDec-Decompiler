TEST(MachoFormatChainedFixups, ImportsComeFromTheFixupChains)
{
	const auto bytes = chainedFixupsMachoBytes();
	MachOFormat parser(bytes.data(), bytes.size());
	ASSERT_TRUE(parser.isInValidState());
	const auto* imports = parser.getImportTable();
	ASSERT_NE(nullptr, imports);
	// Exactly one: the bind in __got. LC_DYSYMTAB must not add a second copy.
	ASSERT_EQ(1u, imports->getNumberOfImports());
	const auto* puts = imports->getImport("_puts");
	ASSERT_NE(nullptr, puts);
	EXPECT_EQ(0x100004000u, puts->getAddress());
}

TEST(MachoFormatChainedFixups, ExportsComeFromTheExportsTrie)
{
	const auto bytes = chainedFixupsMachoBytes();
	MachOFormat parser(bytes.data(), bytes.size());
	const auto* exports = parser.getExportTable();
	ASSERT_NE(nullptr, exports);
	EXPECT_NE(nullptr, exports->getExport("_main"));
}

