static int atoi_table(const char* s)
{
	int n = 0;
	int sign = 1;
	if (*s == '-')
	{
		sign = -1;
		++s;
	}
	while (class_of[(unsigned char)*s])
	{
		n = n * 10 + (*s - 48);
		++s;
	}
	return n * sign;
}

